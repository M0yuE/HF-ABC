from __future__ import annotations

import argparse
import csv
from pathlib import Path
from typing import Dict, List, Mapping, Sequence, Tuple

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import LinearSegmentedColormap


SCENARIOS = ("fully_relaxed", "near_feasible")
METHODS = ("Raw generator", "Clip/Round baseline", "Full Projection")
VIOLATION_ORDER = (
    "seq_len_not_in_legal_set",
    "d_model_not_in_legal_set",
    "n_heads_not_in_legal_set",
    "d_model_not_divisible_by_n_heads",
    "e_layers_not_in_legal_set",
    "d_ff_not_in_legal_set",
    "dropout_out_of_range",
    "learning_rate_out_of_range",
    "batch_size_not_in_legal_set",
    "csg_reduction_active_for_non_csg",
    "csg_reduction_not_in_legal_set",
)

SCENARIO_LABELS = {
    "fully_relaxed": "Fully relaxed",
    "near_feasible": "Near-feasible",
}
METHOD_LABELS = {
    "Raw generator": "Raw",
    "Clip/Round baseline": "Clip/Round",
    "Full Projection": "Projection",
}
VIOLATION_LABELS = {
    "seq_len_not_in_legal_set": "seq_len\nset",
    "d_model_not_in_legal_set": "d_model\nset",
    "n_heads_not_in_legal_set": "n_heads\nset",
    "d_model_not_divisible_by_n_heads": "d_model %\nn_heads",
    "e_layers_not_in_legal_set": "e_layers\nset",
    "d_ff_not_in_legal_set": "d_ff\nset",
    "dropout_out_of_range": "dropout\nrange",
    "learning_rate_out_of_range": "learning rate\nrange",
    "batch_size_not_in_legal_set": "batch_size\nset",
    "csg_reduction_active_for_non_csg": "CSG variable\nactive",
    "csg_reduction_not_in_legal_set": "CSG reduction\nset",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Plot a Nature-style heatmap for projection violation rates.")
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("results/projection_stress_test/projection_violation_breakdown.csv"),
        help="Input projection_violation_breakdown.csv generated by projection_stress_test.py.",
    )
    parser.add_argument(
        "--summary",
        type=Path,
        default=Path("results/projection_stress_test/projection_stress_summary.csv"),
        help="Input projection_stress_summary.csv used to aggregate denominators across seeds.",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("results/projection_stress_test"),
        help="Directory for organized heatmap data and figure files.",
    )
    parser.add_argument(
        "--prefix",
        default="projection_violation_heatmap",
        help="Output filename prefix.",
    )
    return parser.parse_args()


def read_total_candidates(path: Path) -> Dict[Tuple[str, str], int]:
    totals: Dict[Tuple[str, str], int] = {}
    with path.open("r", newline="", encoding="utf-8") as file_obj:
        reader = csv.DictReader(file_obj)
        for row in reader:
            key = (row["scenario"], row["method"])
            totals[key] = totals.get(key, 0) + int(row["num_candidates"])
    return totals


def read_violation_rates(path: Path, total_candidates: Mapping[Tuple[str, str], int]) -> Dict[Tuple[str, str, str], float]:
    counts: Dict[Tuple[str, str, str], int] = {}
    with path.open("r", newline="", encoding="utf-8") as file_obj:
        reader = csv.DictReader(file_obj)
        for row in reader:
            violation_type = row["violation_type"]
            if violation_type == "none":
                continue
            key = (row["scenario"], row["method"], violation_type)
            counts[key] = counts.get(key, 0) + int(row["count"])

    rates: Dict[Tuple[str, str, str], float] = {}
    for (scenario, method, violation_type), count in counts.items():
        denominator = total_candidates.get((scenario, method), 0)
        rates[(scenario, method, violation_type)] = 0.0 if denominator == 0 else count / denominator * 100.0
    return rates


def build_matrix(rates: Mapping[Tuple[str, str, str], float]) -> Tuple[np.ndarray, List[str], List[str]]:
    row_keys = [(scenario, method) for scenario in SCENARIOS for method in METHODS]
    row_labels = [f"{SCENARIO_LABELS[scenario]} | {METHOD_LABELS[method]}" for scenario, method in row_keys]
    col_labels = [VIOLATION_LABELS[name] for name in VIOLATION_ORDER]
    matrix = np.zeros((len(row_keys), len(VIOLATION_ORDER)), dtype=float)
    for row_idx, (scenario, method) in enumerate(row_keys):
        for col_idx, violation_type in enumerate(VIOLATION_ORDER):
            matrix[row_idx, col_idx] = rates.get((scenario, method, violation_type), 0.0)
    return matrix, row_labels, col_labels


def write_matrix_csv(path: Path, matrix: np.ndarray, row_labels: Sequence[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = ["scenario_method", *VIOLATION_ORDER]
    with path.open("w", newline="", encoding="utf-8") as file_obj:
        writer = csv.DictWriter(file_obj, fieldnames=fieldnames)
        writer.writeheader()
        for row_label, row_values in zip(row_labels, matrix):
            row = {"scenario_method": row_label}
            for violation_type, value in zip(VIOLATION_ORDER, row_values):
                row[violation_type] = round(float(value), 4)
            writer.writerow(row)


def write_long_csv(path: Path, matrix: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as file_obj:
        writer = csv.DictWriter(
            file_obj,
            fieldnames=["scenario", "method", "violation_type", "violation_rate_percent"],
        )
        writer.writeheader()
        for row_idx, scenario in enumerate(SCENARIOS):
            for method_idx, method in enumerate(METHODS):
                matrix_row = row_idx * len(METHODS) + method_idx
                for col_idx, violation_type in enumerate(VIOLATION_ORDER):
                    writer.writerow(
                        {
                            "scenario": scenario,
                            "method": method,
                            "violation_type": violation_type,
                            "violation_rate_percent": round(float(matrix[matrix_row, col_idx]), 4),
                        }
                    )


def apply_publication_style() -> None:
    plt.rcParams["font.family"] = "sans-serif"
    plt.rcParams["font.sans-serif"] = ["Arial", "DejaVu Sans", "Liberation Sans"]
    plt.rcParams["svg.fonttype"] = "none"
    plt.rcParams["font.size"] = 8
    plt.rcParams["axes.spines.right"] = False
    plt.rcParams["axes.spines.top"] = False
    plt.rcParams["axes.linewidth"] = 0.8
    plt.rcParams["legend.frameon"] = False


def is_dark_rgba(rgba: Tuple[float, float, float, float]) -> bool:
    r, g, b, _ = rgba
    return (0.299 * r + 0.587 * g + 0.114 * b) < 0.52


def plot_heatmap(matrix: np.ndarray, row_labels: Sequence[str], col_labels: Sequence[str], out_prefix: Path) -> None:
    apply_publication_style()
    cmap = LinearSegmentedColormap.from_list(
        "projection_violation",
        ["#F8FAFC", "#F6CFCB", "#E9A6A1", "#B64342"],
    )

    fig, ax = plt.subplots(figsize=(7.4, 3.55))
    im = ax.imshow(matrix, cmap=cmap, vmin=0, vmax=max(20.0, float(matrix.max())), aspect="auto")

    ax.set_xticks(np.arange(len(col_labels)))
    ax.set_xticklabels(col_labels, rotation=35, ha="right", rotation_mode="anchor")
    ax.set_yticks(np.arange(len(row_labels)))
    ax.set_yticklabels(row_labels)
    ax.set_title("Constraint violation rates under projection diagnostics", pad=10, fontsize=10)

    ax.set_xticks(np.arange(matrix.shape[1] + 1) - 0.5, minor=True)
    ax.set_yticks(np.arange(matrix.shape[0] + 1) - 0.5, minor=True)
    ax.grid(which="minor", color="white", linewidth=1.2)
    ax.tick_params(which="minor", bottom=False, left=False)
    ax.axhline(2.5, color="#272727", linewidth=1.0)

    for row_idx in range(matrix.shape[0]):
        for col_idx in range(matrix.shape[1]):
            value = matrix[row_idx, col_idx]
            if value == 0:
                label = "0"
            elif value < 1:
                label = f"{value:.1f}"
            else:
                label = f"{value:.0f}"
            text_color = "white" if is_dark_rgba(im.cmap(im.norm(value))) else "#272727"
            ax.text(col_idx, row_idx, label, ha="center", va="center", fontsize=6.5, color=text_color)

    cbar = fig.colorbar(im, ax=ax, fraction=0.035, pad=0.025)
    cbar.set_label("Violation rate (%)", rotation=90)
    cbar.outline.set_linewidth(0.6)

    fig.tight_layout(pad=1.0)
    fig.savefig(out_prefix.with_suffix(".svg"), bbox_inches="tight")
    fig.savefig(out_prefix.with_suffix(".png"), dpi=300, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    args = parse_args()
    total_candidates = read_total_candidates(args.summary)
    rates = read_violation_rates(args.input, total_candidates)
    matrix, row_labels, col_labels = build_matrix(rates)
    args.out_dir.mkdir(parents=True, exist_ok=True)

    write_matrix_csv(args.out_dir / f"{args.prefix}_matrix.csv", matrix, row_labels)
    write_long_csv(args.out_dir / f"{args.prefix}_long.csv", matrix)
    plot_heatmap(matrix, row_labels, col_labels, args.out_dir / args.prefix)

    print(f"Wrote organized heatmap data and figures to: {args.out_dir.resolve()}")


if __name__ == "__main__":
    main()
