#!/usr/bin/env python
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

def load_manifest(path: str | Path) -> dict[str, object]:
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run an Optuna-TPE fixed-budget experiment on a prepared water-quality dataset."
    )
    parser.add_argument("--manifest", required=True, help="Path to manifest.json generated by prepare_water_quality_dataset.py")
    parser.add_argument("--dataset_name", default="WQ_GENERIC")
    parser.add_argument("--pred_len", type=int, required=True)
    parser.add_argument("--model_variant", type=str, default="iTransformer_CSG", choices=["iTransformer", "iTransformer_CSG"])
    parser.add_argument("--gpu", type=int, default=0)
    parser.add_argument("--output_dir", type=str, default="./pf_runs_wq_optuna_tpe")
    parser.add_argument("--search_budget", type=int, default=20, help="Fixed Optuna-TPE trial budget.")
    parser.add_argument("--n_trials", type=int, default=None, help="Alias for --search_budget; overrides it when set.")
    parser.add_argument("--search_train_epochs", type=int, default=5)
    parser.add_argument("--search_patience", type=int, default=3)
    parser.add_argument("--final_train_epochs", type=int, default=20)
    parser.add_argument("--final_patience", type=int, default=5)
    parser.add_argument("--search_seeds", type=int, nargs="+", default=[2026])
    parser.add_argument("--final_seeds", type=int, nargs="+", default=[2026, 2027, 2028])
    parser.add_argument("--tpe_startup_trials", type=int, default=10)
    parser.add_argument("--tpe_multivariate", action="store_true")
    parser.add_argument("--tpe_group", action="store_true")
    parser.add_argument("--tpe_constant_liar", action="store_true")
    parser.add_argument("--num_workers", type=int, default=10)
    parser.add_argument("--eval_batch_size", type=int, default=512)
    parser.add_argument("--run_test_during_train", action="store_true")
    parser.add_argument("--use_amp", action="store_true")
    parser.add_argument(
        "--skip_epoch_val",
        dest="skip_epoch_val",
        action="store_true",
        default=True,
        help="Skip validation after every training epoch; enabled by default for HPO consistency.",
    )
    parser.add_argument(
        "--keep_epoch_val",
        dest="skip_epoch_val",
        action="store_false",
        help="Restore per-epoch validation and early stopping behavior.",
    )
    args = parser.parse_args()

    from egta.optuna_tpe import OPTUNA_TPE_METHOD, run_optuna_tpe_experiment
    from pf.runner import ExperimentRunner

    n_trials = int(args.n_trials if args.n_trials is not None else args.search_budget)
    manifest = load_manifest(args.manifest)
    overrides = {
        "root_path": manifest["root_path"],
        "data_path": manifest["data_path"],
        "data": manifest.get("data", "custom"),
        "features": manifest.get("features", "M"),
        "target": manifest.get("target", "OT"),
        "freq": manifest.get("freq", "t"),
        "enc_in": int(manifest["enc_in"]),
        "dec_in": int(manifest["dec_in"]),
        "c_out": int(manifest["c_out"]),
        "feature_columns": manifest.get("feature_columns", []),
        "key_channels": manifest.get("key_channels", []),
        "num_workers": args.num_workers,
        "eval_batch_size": args.eval_batch_size,
        "run_test_during_train": args.run_test_during_train,
        "use_amp": args.use_amp,
        "skip_epoch_val": args.skip_epoch_val,
    }

    runner = ExperimentRunner(
        output_dir=args.output_dir,
        dataset_name=args.dataset_name,
        pred_len=args.pred_len,
        model_name=args.model_variant,
        gpu=args.gpu,
        overrides=overrides,
    )

    result = run_optuna_tpe_experiment(
        base_args=runner.base_args,
        output_dir=args.output_dir,
        model_name=args.model_variant,
        search_space=runner.space,
        search_seeds=args.search_seeds,
        final_seeds=args.final_seeds,
        n_trials=n_trials,
        search_train_epochs=args.search_train_epochs,
        search_patience=args.search_patience,
        final_train_epochs=args.final_train_epochs,
        final_patience=args.final_patience,
        tpe_startup_trials=args.tpe_startup_trials,
        tpe_multivariate=args.tpe_multivariate,
        tpe_group=args.tpe_group,
        tpe_constant_liar=args.tpe_constant_liar,
    )

    summary_path = Path(args.output_dir) / f"water_quality_{args.pred_len}_{args.model_variant}_{OPTUNA_TPE_METHOD}.json"
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path.write_text(json.dumps(result["summary"], ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(result["summary"], ensure_ascii=False, indent=2), flush=True)


if __name__ == "__main__":
    main()
