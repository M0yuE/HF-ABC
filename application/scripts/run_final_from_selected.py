#!/usr/bin/env python
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import sys
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

METRIC_KEYS = ("mse", "mae", "key_mse", "key_mae", "key_rmse")
PF_LEGACY_METHOD = "pf_tahc_abc"
PF_PUBLIC_METHOD = "pf_abc"


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def dump_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2), encoding="utf-8")


def load_manifest(path: str | Path) -> dict[str, object]:
    return load_json(Path(path))


def resolve_methods(method: str) -> tuple[str, str]:
    method = str(method).lower()
    if method in {PF_LEGACY_METHOD, PF_PUBLIC_METHOD}:
        return PF_LEGACY_METHOD, PF_PUBLIC_METHOD
    return method, method


def load_selected_config(output_dir: Path, selected_config_path: str | None) -> tuple[dict[str, object], int | None, float | None]:
    path = Path(selected_config_path) if selected_config_path else output_dir / "selected_best_config.json"
    if not path.exists():
        raise FileNotFoundError(f"selected config file not found: {path}")

    payload = load_json(path)
    if "best_config" in payload:
        config = dict(payload["best_config"])
        source_seed = payload.get("source_search_seed")
        best_score = payload.get("best_score")
    elif "search_summary" in payload and "selected_best_config" in (payload.get("search_summary") or {}):
        search_summary = dict(payload["search_summary"])
        config = dict(search_summary["selected_best_config"])
        source_seed = search_summary.get("selected_search_seed")
        best_score = search_summary.get("selected_val_mse")
    elif "selected_best_config" in payload:
        config = dict(payload["selected_best_config"])
        source_seed = payload.get("selected_search_seed")
        best_score = payload.get("selected_val_mse")
    else:
        config = dict(payload)
        source_seed = None
        best_score = None

    return config, None if source_seed is None else int(source_seed), None if best_score is None else float(best_score)


def ordered_unique(values: list[int]) -> list[int]:
    seen: set[int] = set()
    out: list[int] = []
    for value in values:
        value = int(value)
        if value not in seen:
            seen.add(value)
            out.append(value)
    return out


def merge_final_summary(existing_summary: dict[str, Any] | None, new_rows: list[dict[str, Any]], n_seeds: int) -> dict[str, Any]:
    existing_final = dict((existing_summary or {}).get("final_summary") or {})
    old_n = int(existing_final.get("n_seeds", 0) or 0)
    merged: dict[str, Any] = {"n_seeds": int(n_seeds)}

    for metric in METRIC_KEYS:
        mean_key = f"{metric}_mean"
        std_key = f"{metric}_std"
        count = 0
        total = 0.0
        total_sq = 0.0

        if mean_key in existing_final and old_n > 0:
            old_mean = float(existing_final[mean_key])
            old_std = float(existing_final.get(std_key, 0.0))
            count += old_n
            total += old_n * old_mean
            total_sq += old_n * (old_std * old_std + old_mean * old_mean)

        for row in new_rows:
            if metric not in row:
                continue
            value = float(row[metric])
            count += 1
            total += value
            total_sq += value * value

        if count:
            mean = total / count
            var = max(total_sq / count - mean * mean, 0.0)
            merged[mean_key] = mean
            merged[std_key] = math.sqrt(var)

    return merged


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run final retraining from an existing selected_best_config.json without rerunning search."
    )
    parser.add_argument("--manifest", required=True, help="Path to manifest.json generated by prepare_water_quality_dataset.py")
    parser.add_argument("--dataset_name", default="WQ_GENERIC")
    parser.add_argument("--pred_len", type=int, required=True)
    parser.add_argument("--model_variant", type=str, default="iTransformer", choices=["iTransformer", "iTransformer_CSG"])
    parser.add_argument("--method", type=str, default=PF_PUBLIC_METHOD)
    parser.add_argument("--gpu", type=int, default=0)
    parser.add_argument("--output_dir", required=True, help="Existing run directory that contains selected_best_config.json")
    parser.add_argument("--selected_config", default=None, help="Optional path to selected_best_config.json")
    parser.add_argument("--final_seeds", type=int, nargs="+", required=True)
    parser.add_argument("--final_train_epochs", type=int, default=20)
    parser.add_argument("--final_patience", type=int, default=5)
    parser.add_argument("--num_workers", type=int, default=10)
    parser.add_argument("--eval_batch_size", type=int, default=512)
    parser.add_argument("--run_test_during_train", action="store_true")
    parser.add_argument("--use_amp", action="store_true")
    parser.add_argument(
        "--skip_epoch_val",
        dest="skip_epoch_val",
        action="store_true",
        default=True,
        help="Skip validation after every training epoch; enabled by default for consistency with HPO runs.",
    )
    parser.add_argument(
        "--keep_epoch_val",
        dest="skip_epoch_val",
        action="store_false",
        help="Restore per-epoch validation and early stopping behavior.",
    )
    parser.add_argument("--rerun_existing", action="store_true", help="Rerun a seed even if it is already listed in the summary.")
    args = parser.parse_args()

    from egta.objective import FinalRetrainer
    from pf.runner import ExperimentRunner

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    internal_method, public_method = resolve_methods(args.method)
    summary_path = output_dir / f"{internal_method}_summary.json"
    water_summary_path = output_dir / f"water_quality_{args.pred_len}_{args.model_variant}_{public_method}.json"

    existing_summary = load_json(water_summary_path) if water_summary_path.exists() else None
    if existing_summary is None and summary_path.exists():
        existing_summary = load_json(summary_path)

    selected_config_path = args.selected_config
    if selected_config_path is None and water_summary_path.exists():
        selected_config_path = str(water_summary_path)
    selected_config, selected_search_seed, best_score = load_selected_config(output_dir, selected_config_path)
    if selected_search_seed is None and existing_summary:
        search_summary = existing_summary.get("search_summary") or {}
        selected_search_seed = search_summary.get("selected_search_seed")
        selected_search_seed = None if selected_search_seed is None else int(selected_search_seed)
    if best_score is None and existing_summary:
        search_summary = existing_summary.get("search_summary") or {}
        best_score = search_summary.get("selected_val_mse")
        best_score = None if best_score is None else float(best_score)

    manifest = load_manifest(args.manifest)
    overrides = {
        "root_path": manifest["root_path"],
        "data_path": manifest["data_path"],
        "data": manifest.get("data", "custom"),
        "features": manifest.get("features", "M"),
        "target": manifest.get("target", "OT"),
        "freq": manifest.get("freq", "t"),
        "enc_in": int(manifest["enc_in"]),
        "dec_in": int(manifest["dec_in"]),
        "c_out": int(manifest["c_out"]),
        "feature_columns": manifest.get("feature_columns", []),
        "key_channels": manifest.get("key_channels", []),
        "num_workers": args.num_workers,
        "eval_batch_size": args.eval_batch_size,
        "run_test_during_train": args.run_test_during_train,
        "use_amp": args.use_amp,
        "skip_epoch_val": args.skip_epoch_val,
    }
    runner = ExperimentRunner(
        output_dir=str(output_dir),
        dataset_name=args.dataset_name,
        pred_len=args.pred_len,
        model_name=args.model_variant,
        gpu=args.gpu,
        overrides=overrides,
    )

    existing_final_seeds = [
        int(seed) for seed in ((existing_summary or {}).get("final_seeds") or [])
    ]
    requested_final_seeds = [int(seed) for seed in args.final_seeds]
    seeds_to_run = [
        seed
        for seed in requested_final_seeds
        if args.rerun_existing or seed not in set(existing_final_seeds)
    ]

    new_rows: list[dict[str, Any]] = []
    tag_seed = selected_search_seed if selected_search_seed is not None else "selected"
    for seed in seeds_to_run:
        seed_dir = output_dir / f"final_seed_{seed}"
        seed_dir.mkdir(parents=True, exist_ok=True)
        retrainer = FinalRetrainer(
            runner.base_args,
            output_dir=str(seed_dir),
            final_train_epochs=args.final_train_epochs,
            final_patience=args.final_patience,
        )
        print(f"[FinalOnly] final_seed={seed} | retrain from selected config | start", flush=True)
        row = retrainer.run(selected_config, seed=seed, tag=f"{internal_method}_search{tag_seed}")
        print(f"[FinalOnly] final_seed={seed} | complete", flush=True)
        dump_json(seed_dir / "best_config.json", selected_config)
        dump_json(seed_dir / "final_metrics.json", row)
        new_rows.append(row)

    final_seeds = ordered_unique(existing_final_seeds + requested_final_seeds)
    summary = dict(existing_summary or {})
    summary.setdefault("method", internal_method)
    summary.setdefault("search_seeds", [] if selected_search_seed is None else [selected_search_seed])
    summary["final_seeds"] = final_seeds
    summary.setdefault("search_summary", {})
    if selected_search_seed is not None:
        summary["search_summary"].setdefault("selected_search_seed", selected_search_seed)
    if best_score is not None:
        summary["search_summary"].setdefault("selected_val_mse", best_score)
    summary["search_summary"].setdefault("selected_best_config", selected_config)
    summary["final_summary"] = merge_final_summary(existing_summary, new_rows, n_seeds=len(final_seeds))

    rows_path = output_dir / "final_only_added_rows.json"
    old_added_rows = load_json(rows_path).get("rows", []) if rows_path.exists() else []
    old_added_rows = [row for row in old_added_rows if int(row.get("seed", -1)) not in {int(r["seed"]) for r in new_rows}]
    dump_json(rows_path, {"rows": old_added_rows + new_rows})

    dump_json(summary_path, summary)
    dump_json(water_summary_path, summary)
    print(json.dumps(summary["final_summary"], ensure_ascii=False, indent=2), flush=True)


if __name__ == "__main__":
    main()
